// ### 1. What is the Structure of HTML?
// - HTML (HyperText Markup Language) is the standard language for creating web pages.
// - It has a basic structure to organize and display content on the web.

// ---

// ### 2. Structure of an HTML Document
// 1. **Doctype Declaration**  
//    - `<!DOCTYPE html>`: Tells the browser that the document is written in HTML5.

// 2. **HTML Element**  
//    - `<html>`: The root element that wraps all the content.

// 3. **Head Section**  
//    - `<head>`: Contains metadata (data about the document) such as the title, styles, and links.  
//      Example:  
//      ```html
//      <head>
//        <title>My Webpage</title>
//      </head>
//      ```

// 4. **Body Section**  
//    - `<body>`: Contains the content visible on the webpage, such as headings, paragraphs, images, and links.  
//      Example:  
//      ```html
//      <body>
//        <h1>Welcome!</h1>
//        <p>This is my first webpage.</p>
//      </body>
//      ```

// 5. **Closing Tags**  
//    - Every opening tag (like `<html>`) has a closing tag (like `</html>`).  
//      Example:  
//      ```html
//      <html>
//        <body>
//          <h1>Hello!</h1>
//        </body>
//      </html>
//      ```

// ---

// ### 3. Curious Points 💡
// - The `<title>` in the head section is what appears on the browser tab.  
// - Browsers ignore spaces or tabs in the HTML file—they only focus on tags.  
// - You can add comments in HTML using `<!-- This is a comment -->` to explain your code without displaying it on the page.

